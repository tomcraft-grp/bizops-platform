-- Feedback & Issue system: an English technical context for every issue (builds on 20261114120000_feedback_issue_system).
--
-- The original description is NEVER touched. This only ADDS nullable columns to public.bizops_feedback_issues, so every existing issue stays valid
-- (it simply has no English context yet: status 'pending'):
--   english_context           text     the English, technically structured version (Issue Title ... Acceptance Criteria)
--   english_context_status    text     pending | processing | completed | failed
--   english_context_error     text     why the last attempt failed (never a secret: a short code and message)
--   english_context_at        timestamptz   when the current text was produced
--   english_context_source    text     'ai' (generated) | 'manual' (typed by staff)
--   english_context_model     text     the model that generated it
--   english_context_attempts  integer  how many generations were started
--   english_context_started_at timestamptz when the running generation started (a run older than 5 minutes is treated as dead)
-- Attachments need nothing new: public.feedback_attachments and the private bucket feedback-attachments already exist (same policies).
--
-- Who may do what:
--   * the generator (the Edge Function, running with the service role, after it verified the caller's JWT) uses feedback_english_context_begin /
--     feedback_english_context_finish; no browser can call them;
--   * staff can write or correct the English context by hand: feedback_set_english_context;
--   * reading follows the issue's row-level security (the reporter and staff), exactly like the description.

alter table public.bizops_feedback_issues
  add column if not exists english_context text,
  add column if not exists english_context_status text not null default 'pending',
  add column if not exists english_context_error text,
  add column if not exists english_context_at timestamptz,
  add column if not exists english_context_source text,
  add column if not exists english_context_model text,
  add column if not exists english_context_attempts integer not null default 0,
  add column if not exists english_context_started_at timestamptz;

alter table public.bizops_feedback_issues
  drop constraint if exists feedback_ctx_status_check, drop constraint if exists feedback_ctx_source_check, drop constraint if exists feedback_ctx_length_check;
alter table public.bizops_feedback_issues
  add constraint feedback_ctx_status_check check (english_context_status in ('pending', 'processing', 'completed', 'failed')),
  add constraint feedback_ctx_source_check check (english_context_source is null or english_context_source in ('ai', 'manual')),
  add constraint feedback_ctx_length_check check (english_context is null or length(english_context) <= 20000);

-- the history records who produced or changed an English context (staff only: never shown to the customer)
alter table public.feedback_events drop constraint if exists feedback_events_kind_check;
alter table public.feedback_events add constraint feedback_events_kind_check check (kind in
  ('created', 'status', 'priority', 'category', 'assigned', 'root_cause', 'resolution', 'comment', 'attachment', 'dev_link', 'archived', 'english_context'));

-- ---------------------------------------------------------------------------------------------- generator (service role only)
-- Claims one generation for an issue and returns the facts the generator may use. The caller (the Edge Function) passes the user it verified; the
-- user must be the reporter or support staff. One run at a time per issue; a finished context can be regenerated by staff only.
create or replace function public.feedback_english_context_begin(p_issue text, p_actor uuid)
returns jsonb language plpgsql security definer set search_path = public as $$
declare i public.bizops_feedback_issues; v_staff boolean;
begin
  select * into i from public.bizops_feedback_issues where id = p_issue for update;
  if not found then raise exception 'Feedback not found' using errcode = '42501'; end if;
  v_staff := exists (select 1 from public.profiles p where p.id = p_actor and p.status = 'active' and p.role in ('ADMIN', 'SUPER_ADMIN'));
  if i.reporter_id is distinct from p_actor and not v_staff then raise exception 'Feedback not found' using errcode = '42501'; end if;
  if i.english_context_status = 'processing' and coalesce(i.english_context_started_at, '-infinity') > now() - interval '5 minutes' then
    raise exception 'ALREADY_RUNNING: the English context is being generated'; end if;
  if i.english_context_status = 'completed' and not v_staff then raise exception 'ALREADY_DONE: the English context already exists'; end if;
  update public.bizops_feedback_issues set english_context_status = 'processing', english_context_error = null, english_context_started_at = now(),
    english_context_attempts = english_context_attempts + 1 where id = i.id;
  return jsonb_build_object('id', i.id, 'title', i.title, 'description', i.description, 'category', i.category, 'priority', i.priority, 'source', i.source,
    'page_name', i.page_name, 'page_path', i.page_path, 'module_name', i.module_name, 'app_id', i.app_id, 'app_version', i.app_version,
    'environment', i.environment, 'device_type', i.device_type, 'os_info', i.os_info, 'browser_info', left(coalesce(i.browser_info, ''), 200), 'created_at', i.created_at,
    'attachments', (select coalesce(jsonb_agg(jsonb_build_object('file_name', a.file_name, 'mime_type', a.mime_type, 'size_bytes', a.size_bytes, 'uploaded_at', a.created_at) order by a.created_at), '[]'::jsonb)
                    from public.feedback_attachments a where a.issue_id = i.id and a.comment_id is null));
end $$;

-- Records the outcome. With p_error the attempt failed (the old text, if any, is kept); otherwise the text is stored as AI-generated.
create or replace function public.feedback_english_context_finish(p_issue text, p_context text, p_model text, p_error text default null)
returns void language plpgsql security definer set search_path = public as $$
declare i public.bizops_feedback_issues;
begin
  select * into i from public.bizops_feedback_issues where id = p_issue for update;
  if not found then raise exception 'Feedback not found'; end if;
  if p_error is not null and btrim(p_error) <> '' then
    update public.bizops_feedback_issues set english_context_status = 'failed', english_context_error = left(btrim(p_error), 300) where id = i.id;
    insert into public.feedback_events (issue_id, actor_label, kind, note, customer_visible) values (i.id, 'AI', 'english_context', 'Generation failed: ' || left(btrim(p_error), 200), false);
  else
    if p_context is null or btrim(p_context) = '' or length(p_context) > 20000 then raise exception 'The English context must be 1 to 20,000 characters'; end if;
    update public.bizops_feedback_issues set english_context = btrim(p_context), english_context_status = 'completed', english_context_error = null, english_context_at = now(),
      english_context_source = 'ai', english_context_model = left(p_model, 80) where id = i.id;
    insert into public.feedback_events (issue_id, actor_label, kind, note, customer_visible) values (i.id, 'AI', 'english_context', 'Generated by ' || coalesce(left(p_model, 80), 'AI'), false);
  end if;
end $$;

-- ---------------------------------------------------------------------------------------------- staff: write or correct it by hand
create or replace function public.feedback_set_english_context(p_issue text, p_context text)
returns public.bizops_feedback_issues language plpgsql security definer set search_path = public as $$
declare i public.bizops_feedback_issues;
begin
  if not public.feedback_is_staff() then raise exception 'Only support staff can change the English context' using errcode = '42501'; end if;
  if p_context is null or btrim(p_context) = '' or length(p_context) > 20000 then raise exception 'The English context must be 1 to 20,000 characters'; end if;
  update public.bizops_feedback_issues set english_context = btrim(p_context), english_context_status = 'completed', english_context_error = null, english_context_at = now(),
    english_context_source = 'manual', english_context_model = null where id = p_issue returning * into i;
  if i.id is null then raise exception 'Feedback not found' using errcode = '42501'; end if;
  insert into public.feedback_events (issue_id, actor_id, actor_label, kind, note, customer_visible) values (i.id, auth.uid(), public.feedback_actor_label(), 'english_context', 'Written by hand', false);
  return i;
end $$;

-- ---------------------------------------------------------------------------------------------- grants
revoke execute on function public.feedback_english_context_begin(text, uuid) from public, anon, authenticated;
revoke execute on function public.feedback_english_context_finish(text, text, text, text) from public, anon, authenticated;
revoke execute on function public.feedback_set_english_context(text, text) from public, anon;
grant execute on function public.feedback_set_english_context(text, text) to authenticated;
do $$ begin
  if exists (select 1 from pg_roles where rolname = 'service_role') then
    grant execute on function public.feedback_english_context_begin(text, uuid) to service_role;
    grant execute on function public.feedback_english_context_finish(text, text, text, text) to service_role;
  end if;
end $$;
