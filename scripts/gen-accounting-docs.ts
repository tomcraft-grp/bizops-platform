// Generates the data-backed accounting deliverables from the ACTUAL configuration (so the documents cannot drift from the system).
// Run: npx tsx scripts/gen-accounting-docs.ts   → docs/accounting/*.csv and the generated blocks of the registers.
import { mkdirSync, writeFileSync } from 'node:fs';
import { buildSeed } from '../src/domain/seed';
import { ROLE_DEFS } from '../src/domain/accounting';
import { coaToRows, reconciliationMatrix, setupChecks } from '../src/domain/setup';
import type { DB } from '../src/domain/types';

const NOW = new Date('2026-11-13T10:30:00+07:00');
const db = buildSeed(NOW) as DB;
const OUT = 'docs/accounting';
mkdirSync(OUT, { recursive: true });
const csv = (rows: (string | number)[][]) => '﻿' + rows.map((r) => r.map((c) => { const s = String(c ?? ''); return /[",\n]/.test(s) ? '"' + s.replace(/"/g, '""') + '"' : s; }).join(',')).join('\r\n') + '\r\n';
const VERSION = 'v1.0';

// 1. Chart of accounts (same columns the importer accepts)
writeFileSync(`${OUT}/CHART_OF_ACCOUNTS.csv`, csv(coaToRows(db)));

// 2. Transaction → account mapping (role registry + current versioned mapping + what each role is used by)
const mapRows: (string | number)[][] = [['posting_role', 'label', 'default_account', 'current_account', 'current_account_name', 'effective_from', 'expected_fs_line', 'business_events_using_this_role']];
for (const r of ROLE_DEFS) {
  const cur = db.postingMap[r.key]?.slice().sort((a, b) => b.from.localeCompare(a.from))[0];
  const acct = db.accounts.find((a) => a.code === cur?.code);
  mapRows.push([r.key, r.label, r.def, cur?.code ?? '', acct?.name ?? '', cur?.from?.slice(0, 10) ?? '', r.expect.join(' | '), r.events]);
}
writeFileSync(`${OUT}/TRANSACTION_ACCOUNT_MAPPING.csv`, csv(mapRows));

// 3. Opening balance template: every postable, non-control, non-contra-system account; control accounts must come from documents
const posting = db.accounts.filter((a) => a.posting && a.active !== false && !a.control);
const ob: (string | number)[][] = [['account_code', 'account_name', 'normal_balance', 'debit', 'credit', 'source_reference', 'preparer_note']];
for (const a of posting) ob.push([a.code, a.name, a.normal, '', '', '', '']);
writeFileSync(`${OUT}/OPENING_BALANCE_TEMPLATE.csv`, csv(ob));
const controls = db.accounts.filter((a) => a.control);

// 4. Generated blocks for registers (pasted into the markdown by the build step below)
const tax = ['| Code | Name | Kind | Rate | Creditable | Effective from | Version |', '|---|---|---|---|---|---|---|', ...db.taxCodes.map((t) => `| ${t.code} | ${t.name} | ${t.kind} | ${(t.rate * 100).toFixed(2)}% | ${t.creditable ? 'yes' : 'no'} | ${t.effectiveFrom.slice(0, 10)} | ${t.version} |`)].join('\n');
const recon = reconciliationMatrix(db);
const reconMd = ['| Control | GL accounts | GL balance | Subledger / source | Subledger amount | Difference | Status (demo data) |', '|---|---|---:|---|---:|---:|---|', ...recon.map((r) => `| ${r.title} | ${r.accounts} | ${r.gl.toFixed(2)} | ${r.subLabel} | ${r.sub.toFixed(2)} | ${r.diff.toFixed(2)} | ${r.status} |`)].join('\n');
const checks = setupChecks(db);
const setupMd = ['| Stage | Check | Status | Detail |', '|---|---|---|---|', ...checks.map((c) => `| ${c.stage} | ${c.title} | ${c.status} | ${String(c.detail).replace(/\|/g, '/')} |`)].join('\n');
const roleMd = ['| Role | Label | Default | Current | Effective from | Business events |', '|---|---|---|---|---|---|', ...ROLE_DEFS.map((r) => { const cur = db.postingMap[r.key]?.slice().sort((a, b) => b.from.localeCompare(a.from))[0]; return `| \`${r.key}\` | ${r.label} | ${r.def} | ${cur?.code ?? '—'} | ${cur?.from?.slice(0, 10) ?? '—'} | ${r.events} |`; })].join('\n');

console.log('accounts', db.accounts.length, 'roles', ROLE_DEFS.length, 'tax codes', db.taxCodes.length, 'opening-template rows', ob.length - 1, 'control accounts', controls.length);
console.log(JSON.stringify({ tax, reconMd, setupMd, roleMd }).length, 'chars of generated markdown blocks');

// 5. Fill the generated blocks inside the hand-written documents (idempotent: replaces whatever is between the markers)
import { readFileSync, existsSync } from 'node:fs';
const fill = (file: string, name: string, body: string) => {
  const p = `${OUT}/${file}`;
  if (!existsSync(p)) return;
  const s = readFileSync(p, 'utf8');
  const re = new RegExp(`(<!-- BEGIN:${name} -->)[^]*?(<!-- END:${name} -->)`);
  if (!re.test(s)) { console.log('marker missing', file, name); return; }
  writeFileSync(p, s.replace(re, `$1\n_Generated by scripts/gen-accounting-docs.ts from the seeded demo business (fixed date 2026-11-13). Do not edit by hand._\n\n${body}\n$2`));
};
fill('ACCOUNTING_SETUP_GUIDE.md', 'setup', setupMd);
fill('TAX_CONFIGURATION_REGISTER.md', 'tax', tax);
fill('TRANSACTION_ACCOUNT_MAPPING.md', 'roles', roleMd);
fill('ACCOUNTING_RECONCILIATION_MATRIX.md', 'recon', reconMd);
